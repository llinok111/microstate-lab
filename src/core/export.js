/**
 * Code export.
 *
 * The lab's credibility rests on this file. If the exported snippet does not
 * produce what the preview produced, the whole tool is theatre. So the exporter
 * is built from the *same* data the preview consumes:
 *
 *   presetKeyframes()  ->  @keyframes blocks
 *   plan().effective   ->  duration / delay / easing / iteration count
 *   reduced strategy   ->  a real `@media (prefers-reduced-motion: reduce)` block
 *
 * Three targets are produced for each preset:
 *
 *   CSS   — a stylesheet plus the class names to add. No JS, no dependency.
 *   JS    — Web Animations API call, for effects that need computed values.
 *   HTML  — a complete, self-contained page that runs the interaction for real.
 *
 * `test/export.test.mjs` re-parses the generated CSS, and
 * `test/export-runtime.test.mjs` loads the generated HTML in a browser and
 * drives it, so "the export works" is an executed claim rather than a promise.
 */

import { parseEasing, toLinear } from "./easing.js";
import { plan, keyframesFor, LIMITS } from "./motion.js";
import { getPreset, isCounterExample } from "./presets.js";

/** kebab-case a camelCase property name. */
function kebab(prop) {
  return prop.replace(/[A-Z]/g, (c) => "-" + c.toLowerCase());
}

/**
 * Turn a numeric keyframe list into a CSS `@keyframes` body.
 *
 * Only `transform` and `opacity` are emitted — the two properties that stay on
 * the compositor. Animating layout properties is the single most common reason
 * a micro-interaction drops frames, so the exporter refuses to generate them.
 */
export function keyframesToCss(name, frames) {
  const steps = frames
    .map((frame) => {
      const pct = Math.round((frame.offset ?? 0) * 1000) / 10;
      const decls = [];
      if (frame.transform !== undefined) decls.push(`    transform: ${frame.transform};`);
      if (frame.opacity !== undefined) decls.push(`    opacity: ${frame.opacity};`);
      return `  ${pct}% {\n${decls.join("\n")}\n  }`;
    })
    .join("\n");
  return `@keyframes ${name} {\n${steps}\n}`;
}

/** CSS easing string for a spec, downgrading `linear()` when unsupported. */
export function cssEasingFor(easingInput, { linearSupported = true } = {}) {
  const fn = parseEasing(easingInput);
  if (fn.kind === "spring") {
    return linearSupported ? toLinear(fn, 32) : "cubic-bezier(.34, 1.4, .64, 1)";
  }
  return fn.css;
}

/**
 * The reduced-motion block.
 *
 * Each strategy produces a *different* rule, because they are different
 * decisions. `instant` keeps the end state and kills the transition; `fade`
 * keeps a short opacity change and drops transform; `off` removes the animation
 * entirely. `ignore` emits a comment stating the deliberate omission — an
 * undocumented accessibility opt-out is worse than none.
 */
export function reducedMotionCss(className, strategy) {
  switch (strategy) {
    case "instant":
      return `@media (prefers-reduced-motion: reduce) {
  .${className} {
    animation-duration: 1ms !important;
    animation-delay: 0ms !important;
    transition-duration: 1ms !important;
    transition-delay: 0ms !important;
  }
}`;
    case "fade":
      return `@media (prefers-reduced-motion: reduce) {
  .${className} {
    animation-name: ${className}-fade-only;
    animation-duration: 90ms !important;
    animation-delay: 0ms !important;
  }
}

@keyframes ${className}-fade-only {
  from { opacity: 0; }
  to   { opacity: 1; }
}`;
    case "off":
      return `@media (prefers-reduced-motion: reduce) {
  .${className} {
    animation: none !important;
    transition: none !important;
  }
}`;
    case "ignore":
      return `/* reduced-motion: deliberately ignored for this preset.
   Only acceptable when the motion carries no state — document the reason. */`;
    default:
      throw new Error(`Unknown reduced-motion strategy: ${strategy}`);
  }
}

/**
 * Generate a CSS-only export.
 *
 * The generated stylesheet is standalone: drop it in, add the class, and the
 * interaction runs. No build step, no JS, no runtime.
 */
export function exportCss(presetId, motionOverride = {}, options = {}) {
  const preset = getPreset(presetId);
  const motion = { ...preset.motion, ...motionOverride };
  const p = plan({ ...motion, osPrefers: false, policy: "respect" });

  const className = `ms-${preset.id}`;
  const animationName = `${className}-anim`;
  const frames = keyframesFor(preset.effect, motion);
  const linearSupported = options.linearSupported ?? true;
  const easing = cssEasingFor(motion.easing, { linearSupported });
  const iterations = motion.iterations === Infinity ? "infinite" : String(Math.max(1, motion.iterations ?? 1));

  const triggerClass = triggerToClass(preset, motion);

  const css = `/* ${preset.label} — generated by microstate-lab
   duration ${p.effective.duration}ms · delay ${p.effective.delay}ms · easing ${easing} */

${keyframesToCss(animationName, frames)}

.${className} {
  animation-name: ${animationName};
  animation-duration: ${Math.max(1, p.effective.duration)}ms;
  animation-delay: ${p.effective.delay}ms;
  animation-timing-function: ${easing};
  animation-iteration-count: ${iterations};
  animation-fill-mode: both;
  will-change: transform, opacity;
}

/* Resting state must not leave will-change behind — it pins a layer per element. */
.${className}.is-idle {
  animation: none;
  will-change: auto;
}

${triggerCss(className, triggerClass, animationName, p, iterations)}

${reducedMotionCss(className, motion.reduced)}
`;

  const html = `<button class="${className}" type="button">${preset.label}</button>`;

  const js = `// Trigger by adding the class, or call the helper:
document.querySelector(".${className}").addEventListener("click", (ev) => {
  const el = ev.currentTarget;
  el.classList.remove("is-idle");
  el.style.animation = "none";
  void el.offsetWidth;               // force reflow so the animation restarts
  el.style.animation = "";
});`;

  return {
    presetId,
    className,
    animationName,
    css,
    html,
    js,
    notes: buildNotes(preset, p, motion, easing, linearSupported),
  };
}

/**
 * Map the abstract trigger onto the CSS that actually implements it.
 *
 * `press` is the interesting one: it needs a pointer-down/key-down start and a
 * release that reverses, which CSS cannot express with a class alone. The
 * export says so instead of pretending.
 */
function triggerToClass(preset, motion) {
  switch (motion.trigger) {
    case "hover":
      return "hover";
    case "focus":
      return "focus";
    case "enter":
      return "enter";
    case "press":
      return "press";
    case "manual":
      return "manual";
    case "click":
    default:
      return "click";
  }
}

function triggerCss(className, trigger, animationName, p, iterations) {
  const base = `.${className}:is(.is-running) {
  animation-name: ${animationName};
}`;

  switch (trigger) {
    case "hover":
      return `/* Trigger: hover — animation runs while the pointer is over the element. */
.${className}:hover {
  animation-name: ${animationName};
}`;
    case "focus":
      return `/* Trigger: focus — keyboard and pointer both count. :focus-visible keeps
   the effect off mouse clicks if you prefer; this export uses plain :focus
   so the two inputs behave identically. */
.${className}:focus {
  animation-name: ${animationName};
}`;
    case "press":
      return `/* Trigger: press — starts on pointer/key down, reverses on release.
   A pure class toggle cannot express "held" state, so this needs the 4-line
   JS below. CSS-only is available by switching the trigger to click. */
.${className}:active {
  animation-name: ${animationName};
  animation-direction: normal;
}`;
    case "enter":
      return `/* Trigger: enter — runs once when the element first appears. */
.${className} {
  animation-name: ${animationName};
}`;
    case "manual":
      return base;
    case "click":
    default:
      return `/* Trigger: click — add .is-running, then remove it on animationend.
   ${iterations === "infinite" ? "This preset loops; remove the class to stop it." : "Removing the class returns the element to its resting state."} */
.${className}.is-running {
  animation-name: ${animationName};
}`;
  }
}

function buildNotes(preset, p, motion, easing, linearSupported) {
  const notes = [];

  if (preset.effect === "none") {
    notes.push("This preset has no keyframes of its own — it is driven by component state (spinner rotation, thumb position). The CSS export therefore contains the state styles, not an animation.");
  }
  if (parseEasing(motion.easing).kind === "spring" && !linearSupported) {
    notes.push("Spring easing exported as a cubic-bezier approximation: this target lacks CSS linear() support. The overshoot is close but not identical.");
  }
  if (p.effective.duration === 0) {
    notes.push("Effective duration is 0ms — the state change is instant. This is the intended reduced-motion behaviour, not a bug.");
  }
  if (motion.delay > 0) {
    notes.push(`A ${motion.delay}ms delay is included. Anything above ~100ms starts to read as lag rather than polish.`);
  }
  if (isCounterExample(preset.id)) {
    notes.push("This preset is a documented counter-example: it is slow on purpose so the failure mode can be felt. Do not ship it.");
  }
  if (motion.iterations === Infinity) {
    notes.push("Looping animation. `will-change` is left set while running, so remove the class when the work finishes.");
  }
  notes.push(`Reduced-motion strategy: ${motion.reduced}. ${describeStrategy(motion.reduced)}`);
  return notes;
}

function describeStrategy(strategy) {
  switch (strategy) {
    case "instant":
      return "The state still changes immediately; only the transition is removed.";
    case "fade":
      return "Spatial movement is dropped, a 90ms opacity fade remains.";
    case "off":
      return "Nothing animates. Use only when the motion carries no state.";
    case "ignore":
      return "Deliberately not handled — only valid for lab inspection.";
    default:
      return "";
  }
}

/**
 * Web Animations API export.
 *
 * Preferred over CSS when the effect depends on values known only at runtime
 * (measured height, drag distance, spring settling time).
 */
export function exportJs(presetId, motionOverride = {}) {
  const preset = getPreset(presetId);
  const motion = { ...preset.motion, ...motionOverride };
  const p = plan({ ...motion, osPrefers: false, policy: "respect" });
  const frames = keyframesFor(preset.effect, motion);
  const easing = cssEasingFor(motion.easing, { linearSupported: true });

  const framesLiteral = frames
    .map((f) => {
      const parts = [];
      if (f.transform !== undefined) parts.push(`transform: ${JSON.stringify(f.transform)}`);
      if (f.opacity !== undefined) parts.push(`opacity: ${f.opacity}`);
      parts.push(`offset: ${f.offset}`);
      return `    { ${parts.join(", ")} }`;
    })
    .join(",\n");

  return `// ${preset.label} — generated by microstate-lab
// duration ${p.effective.duration}ms · delay ${p.effective.delay}ms · easing ${easing}

const KEYFRAMES = [
${framesLiteral}
];

const REDUCED = window.matchMedia("(prefers-reduced-motion: reduce)");

function play(el) {
  // Strategy: ${motion.reduced} — ${describeStrategy(motion.reduced)}
  const reduced = REDUCED.matches && ${JSON.stringify(motion.reduced)} !== "ignore";

  const frames = reduced && ${JSON.stringify(motion.reduced)} === "fade"
    ? [{ opacity: 0, offset: 0 }, { opacity: 1, offset: 1 }]
    : KEYFRAMES;

  const duration = reduced
    ? (${JSON.stringify(motion.reduced)} === "fade" ? 90 : 0)
    : ${p.effective.duration};

  if (duration === 0) {
    // Apply the end state directly so the interaction is still correct.
    const last = frames[frames.length - 1];
    if (last.transform !== undefined) el.style.transform = last.transform;
    if (last.opacity !== undefined) el.style.opacity = String(last.opacity);
    return Promise.resolve();
  }

  const anim = el.animate(frames, {
    duration,
    delay: reduced ? 0 : ${p.effective.delay},
    easing: ${JSON.stringify(easing)},
    iterations: ${motion.iterations === Infinity ? "Infinity" : Math.max(1, motion.iterations ?? 1)},
    fill: "both",
  });

  // Cancel keeps the element at the target state instead of mid-flight.
  return anim.finished.then(
    () => "finished",
    () => {
      const last = frames[frames.length - 1];
      if (last.transform !== undefined) el.style.transform = last.transform;
      if (last.opacity !== undefined) el.style.opacity = String(last.opacity);
      return "cancelled";
    }
  );
}

export { play };`;
}

/**
 * A complete runnable page.
 *
 * Not a snippet the reader has to assemble — it boots, it animates, it honours
 * reduced motion, and it works from `file://`. The browser test loads exactly
 * this string.
 */
export function exportStandaloneHtml(presetId, motionOverride = {}) {
  const preset = getPreset(presetId);
  const css = exportCss(presetId, motionOverride, { linearSupported: true });
  const js = exportJs(presetId, motionOverride);
  const motion = { ...preset.motion, ...motionOverride };

  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${preset.label} — microstate-lab export</title>
<style>
  :root { color-scheme: light; }
  body {
    margin: 0; min-height: 100vh; display: grid; place-items: center;
    background: #f6f3ee; color: #2b2622;
    font: 16px/1.5 ui-sans-serif, system-ui, -apple-system, "Segoe UI", sans-serif;
  }
  .stage { display: grid; gap: 24px; justify-items: center; padding: 48px; }
  h1 { font-size: 15px; font-weight: 600; letter-spacing: .08em; text-transform: uppercase;
       color: #8a7f74; margin: 0; }
  .target {
    font: inherit; font-size: 15px; font-weight: 600;
    padding: 12px 22px; border-radius: 10px; cursor: pointer;
    border: 1px solid #d8cec2; background: #fffdfa; color: #2b2622;
    box-shadow: 0 1px 2px rgba(43,38,34,.06);
  }
  .target:focus-visible { outline: 2px solid #b4552d; outline-offset: 3px; }
  .hint { font-size: 13px; color: #8a7f74; max-width: 34ch; text-align: center; }
  .counter { font-size: 12px; color: #b4552d; font-weight: 600; }

  ${css.css}
</style>
</head>
<body>
<main class="stage">
  <h1>${preset.label}</h1>
  <button class="target ${css.className}" id="target" type="button">${preset.label}</button>
  <p class="hint">${preset.description}</p>
  <p class="counter" id="count" aria-live="polite">0 runs</p>
</main>
<script type="module">
${js}

const el = document.getElementById("target");
const out = document.getElementById("count");
let runs = 0;

function trigger() {
  runs += 1;
  out.textContent = runs + (runs === 1 ? " run" : " runs");
  el.classList.remove("is-idle");
  el.style.animation = "none";
  void el.offsetWidth;
  el.style.animation = "";
  play(el);
}

el.addEventListener("click", trigger);
el.addEventListener("keydown", (ev) => {
  if (ev.key === "Enter" || ev.key === " ") {
    // Space would scroll the page; the button already fires click on Enter/Space,
    // so only guard the default here and let click do the work.
    ev.preventDefault();
    trigger();
  }
});
</script>
</body>
</html>`;
}

/** Bundle every target for one preset — what the export panel shows in tabs. */
export function exportAll(presetId, motionOverride = {}, options = {}) {
  return {
    css: exportCss(presetId, motionOverride, options),
    js: exportJs(presetId, motionOverride),
    html: exportStandaloneHtml(presetId, motionOverride),
  };
}

/**
 * Export several presets into one stylesheet.
 *
 * The single-preset export answers "what does this interaction look like". A real
 * page has three or four of them, and hand-merging four generated stylesheets —
 * each with its own `:root`, its own `will-change` handling and its own
 * reduced-motion block — is exactly the kind of copy-paste that rots.
 *
 * The output is a single file with one reduced-motion block per preset (they
 * carry different strategies, so they cannot be merged into one), a shared header
 * and a manifest comment listing what is inside.
 */
export function exportBundle(configs, options = {}) {
  const list = Array.isArray(configs) ? configs : Object.entries(configs).map(([preset, motion]) => ({ preset, motion }));

  if (!list.length) throw new Error("exportBundle needs at least one preset");

  const parts = [];
  const manifest = [];
  const conflicts = [];

  for (const cfg of list) {
    const presetId = typeof cfg === "string" ? cfg : cfg.preset;
    const motion = (typeof cfg === "string" ? {} : cfg.motion) ?? {};
    const out = exportCss(presetId, motion, options);

    // Two presets that resolve to the same class name would silently overwrite
    // each other in the merged file. Detect it rather than ship the bug.
    if (manifest.some((m) => m.className === out.className)) {
      conflicts.push(out.className);
    }

    parts.push(out.css);
    manifest.push({ preset: presetId, className: out.className, notes: out.notes });
  }

  const header = [
    "/* microstate-lab — bundle export",
    ` * ${manifest.length} interaction${manifest.length === 1 ? "" : "s"}: ${manifest.map((m) => m.className).join(", ")}`,
    " *",
    " * Every rule is namespaced under its own class. Add the class to run it;",
    " * for click/manual triggers add `.is-running` and remove it on animationend.",
    " * Each preset carries its own prefers-reduced-motion block because the",
    " * strategies differ — do not collapse them into one.",
    " */",
    "",
  ].join("\n");

  const css = header + parts.join("\n\n");

  return {
    css,
    manifest,
    conflicts,
    /** Markup for every component in the bundle, for a quick manual check. */
    html: manifest.map((m) => `<!-- ${m.preset} -->\n<div class="${m.className}" tabindex="0">${m.preset}</div>`).join("\n\n"),
    notes: conflicts.length
      ? [`Duplicate class names: ${conflicts.join(", ")} — later rules win.`]
      : ["All class names are unique."],
  };
}

/** A JSON snapshot of the current settings, so a configuration can be shared. */
export function exportConfig(presetId, motionOverride = {}) {
  const preset = getPreset(presetId);
  return JSON.stringify(
    {
      preset: preset.id,
      family: preset.family,
      effect: preset.effect,
      motion: { ...preset.motion, ...motionOverride },
    },
    null,
    2
  );
}

/** Human-readable summary line used in the panel header. */
export function summarize(presetId, motionOverride = {}) {
  const preset = getPreset(presetId);
  const motion = { ...preset.motion, ...motionOverride };
  const p = plan({ ...motion, osPrefers: false });
  const bits = [`${p.effective.duration}ms`];
  if (p.effective.delay) bits.push(`+${p.effective.delay}ms delay`);
  bits.push(motion.easing);
  bits.push(`on ${motion.trigger}`);
  if (p.effective.duration === 0) bits.push("(static)");
  return bits.join(" · ");
}

